#!/usr/bin/env bun
/**
 * Write the Homebrew formula for a release, from the checksums the release build produced.
 *
 *   bun scripts/homebrew-formula.ts <version> [SHA256SUMS] [download base URL] > ngobe.rb
 *
 * The release workflow commits the result to github.com/ngobe-ai/homebrew-tap as
 * Formula/ngobe.rb, so users can `brew install ngobe-ai/tap/ngobe`.
 */
import fs from "node:fs";

const [version, sumsFile = "dist-bin/SHA256SUMS", baseArg] = process.argv.slice(2);
if (!version || !/^\d+\.\d+\.\d+/.test(version)) {
  console.error("usage: bun scripts/homebrew-formula.ts <version> [SHA256SUMS] [base URL]");
  process.exit(2);
}
const base = baseArg ?? `https://github.com/ngobe-ai/ngobe-cli/releases/download/v${version}`;
const sums = new Map(
  fs
    .readFileSync(sumsFile, "utf8")
    .trim()
    .split("\n")
    .map((line) => {
      const [hash, file] = line.trim().split(/\s+/);
      return [file, hash] as const;
    }),
);
const asset = (target: string) => {
  const file = `ngobe-${target}.tar.gz`;
  const hash = sums.get(file);
  if (!hash) throw new Error(`${file} is missing from ${sumsFile}`);
  return `      url "${base}/${file}"\n      sha256 "${hash}"`;
};

process.stdout.write(`# Generated by scripts/homebrew-formula.ts in ngobe-ai/ngobe-cli. Do not edit by hand.
class Ngobe < Formula
  desc "Coding agent for local models with live, official-source verification"
  homepage "https://github.com/ngobe-ai/ngobe-cli"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${asset("darwin-arm64")}
    end
    on_intel do
${asset("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${asset("linux-arm64")}
    end
    on_intel do
${asset("linux-x64")}
    end
  end

  def install
    bin.install "ngobe"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ngobe --version")
  end
end
`);
